CREATE TABLE IF NOT EXISTS image_report (
	image_id UUID
		NOT NULL
		REFERENCES image (id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
		DEFERRABLE INITIALLY IMMEDIATE,
	
	player_id UUID
		NOT NULL
		REFERENCES player (id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
		DEFERRABLE INITIALLY IMMEDIATE,
	
	reason Text,

	PRIMARY KEY (image_id, player_id)
);